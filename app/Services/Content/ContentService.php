namespace App\Services\Content;

use App\Enums\AiCallKind;
use App\Enums\AiPurpose;
use App\Enums\ContentStatus;
use App\Enums\ContentType;
use App\Enums\Plan;
use App\Jobs\GenerateContentJob;
use App\Models\AiCall;
use App\Models\ContentPiece;
use App\Models\Hotel;
use App\Models\HotelFact;
use App\Models\Recommendation;
use App\Models\Team;
use App\Models\User;
use App\Services\Budget\AiCallContext;
use App\Services\Budget\AiSpend;
use App\Services\Budget\BudgetExceeded;
use App\Services\Budget\BudgetGuard;
use App\Services\Budget\TeamCostCap;
use App\Services\Insights\Accuracy\AccuracyService;
use App\Services\Plans\PlanLimits;
use App\Services\Recommendations\RecommendationReport;
use App\Services\Scanning\CostCalculator;
use App\Services\Trials\TrialLocks;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Str;

/**
 * "Create content" on a recommendation: plan allowance, versions, the
 * generation itself (one AI call per piece; schema markup from facts only),
 * and edits. Every piece uses only the hotel's data and facts; FactGuard
 * flags any number the facts do not contain.
 */
final class ContentService
{
    public function __construct(
        private readonly AccuracyService $accuracy,
        private readonly ContentWriter $writer,
        private readonly SchemaMarkupBuilder $schema,
        private readonly CostCalculator $costs,
        private readonly OtaChecklistBuilder $otaChecklist,
    ) {}

    /**
     * Pieces created this month (team timezone) across the team's hotels.
     *
     * @return array{used: int, limit: ?int, left: ?int, unlimited: bool}
     */
    public function allowance(Hotel $hotel, User $user): array
    {
        $team = $hotel->team;
        $limit = ($team?->limits() ?? PlanLimits::for(Plan::Starter))->contentGenerationsPerMonth;
        $used = ContentPiece::query()
            ->whereIn('hotel_id', $team ? $team->hotels()->pluck('id') : [$hotel->id])
            ->where('created_at', '>=', $team?->currentPeriodStart() ?? now()->startOfMonth())
            ->where('status', '!=', ContentStatus::Failed->value)
            ->count();

        if ($user->is_admin) {
            return ['used' => $used, 'limit' => null, 'left' => null, 'unlimited' => true];
        }

        return ['used' => $used, 'limit' => $limit, 'left' => max(0, $limit - $used), 'unlimited' => false];
    }

    /**
     * Languages the hotel's prompts use, English first.
     *
     * @return array<string, string> code => name
     */
    public function languages(Hotel $hotel): array
    {
        $names = (array) config('citevanta.languages', []);
        $codes = collect(['en', ...$hotel->prompts()->distinct()->pluck('language')->all()])->filter()->unique();

        return $codes->mapWithKeys(fn ($code) => [$code => $names[$code] ?? strtoupper($code)])->all();
    }

    /**
     * Start a new version. Schema markup is built at once; other types are
     * generated by GenerateContentJob (one AI call).
     *
     * @throws ContentLimitReached
     */
    public function request(Recommendation $recommendation, ContentType $type, string $language, User $user): ContentPiece
    {
        $hotel = $recommendation->hotel;
        $language = array_key_exists($language, $this->languages($hotel)) ? $language : 'en';

        if (! $user->is_admin && $hotel->team?->isReadOnly()) {
            throw ContentLimitReached::readOnly();
        }

        if (! $user->is_admin && app(TrialLocks::class)->isRecommendationLocked($hotel, $recommendation->id)) {
            throw new ContentLimitReached(null, TrialLocks::message(app(RecommendationReport::class)->openCount($hotel)).'.');
        }

        if (! $type->isTemplate()) {
            $this->checkBudget($hotel);
        }

        $piece = DB::transaction(function () use ($recommendation, $hotel, $type, $language, $user) {
            $allowance = $this->allowance($hotel, $user);

            if (! $allowance['unlimited'] && $allowance['left'] <= 0) {
                throw new ContentLimitReached($allowance['limit']);
            }

            $version = (int) $recommendation->contentPieces()->where('type', $type->value)->where('language', $language)->max('version') + 1;

            return $recommendation->contentPieces()->create([
                'hotel_id' => $hotel->id,
                'created_by' => $user->id,
                'type' => $type,
                'language' => $language,
                'version' => $version,
                'status' => ContentStatus::Pending,
            ]);
        });

        if ($type->isTemplate()) {
            $this->generate($piece);
        } else {
            GenerateContentJob::dispatch($piece->id);
        }

        return $piece->fresh();
    }

    /**
     * Refuse before creating a piece the budget or the team's cost cap would block.
     *
     * @throws ContentLimitReached
     */
    private function checkBudget(Hotel $hotel): void
    {
        $team = $hotel->team;
        $estimate = app(AiSpend::class)->estimate(AiCallKind::Content);

        if ($team !== null && app(TeamCostCap::class)->exceeded($team, $estimate)) {
            throw new ContentLimitReached(null, TeamCostCap::MESSAGE);
        }

        try {
            app(BudgetGuard::class)->authorize(AiCallContext::forTeam($team, $hotel->id), AiCallKind::Content);
        } catch (BudgetExceeded $e) {
            throw new ContentLimitReached(null, in_array($e->reason, [BudgetExceeded::TEAM_KEY, BudgetExceeded::TEAM_BUDGET], true)
                ? $e->getMessage()
                : 'Content generation is paused for a while because of high demand. Please try again later.');
        }
    }

    public function inputFor(ContentPiece $piece): ContentInput
    {
        $hotel = $piece->hotel;
        $recommendation = $piece->recommendation;
        $facts = $this->accuracy->factsFor($hotel);
        $filled = collect($facts)->keys()->map(fn ($k) => Str::lower($k))->all();
        $missing = collect(HotelFact::suggestedKeys())
            ->merge($hotel->accuracyIssues()->missingFacts()->where('status', 'open')->pluck('fact_key'))
            ->map(fn ($k) => Str::lower((string) $k))
            ->reject(fn ($k) => in_array($k, $filled, true))
            ->unique()->values()->all();

        return new ContentInput(
            type: $piece->type,
            language: $piece->language,
            languageName: (string) (config("citevanta.languages.{$piece->language}") ?? 'English'),
            hotel: [
                'name' => $hotel->name,
                'city' => $hotel->city,
                'country' => $hotel->country,
                'website' => $hotel->website,
                'type' => $hotel->hotel_type,
                'stars' => $hotel->star_rating ? (string) $hotel->star_rating : null,
            ],
            facts: $facts,
            missingFacts: $missing,
            topic: (string) ($recommendation?->title ?? $piece->type->label()),
            why: (string) ($recommendation?->why ?? ''),
        );
    }

    /**
     * Generate a pending piece (one AI call, except schema markup).
     */
    public function generate(ContentPiece $piece): void
    {
        if ($piece->status !== ContentStatus::Pending) {
            return;
        }

        if ($piece->type === ContentType::SchemaJsonLd) {
            $piece->update([
                'status' => ContentStatus::Ready,
                'title' => 'Schema markup (JSON-LD) for '.$piece->hotel->name,
                'body' => $this->schema->build($piece->hotel, $this->accuracy->factsFor($piece->hotel)),
            ]);

            return;
        }

        $input = $this->inputFor($piece);
        $result = app(BudgetGuard::class)->run(
            AiCallContext::forTeam($piece->hotel->team, $piece->hotel_id),
            AiCallKind::Content,
            fn () => $this->writer->write($input),
            fn (array $result) => [(string) $result['model'], (int) $result['tokens_in'], (int) $result['tokens_out']],
        );
        $body = FactGuard::check($result['body'], $input->sources());

        // OTA listing update: part 1 (the checklist) is built from facts and evidence, part 2 is the AI text.
        if ($piece->type === ContentType::OtaListingUpdate) {
            $body = $this->otaChecklist->build($piece->hotel, $piece->recommendation, $input->facts)."\n\n".$body;
        }

        // A team cost (Admin > Teams), never part of a scan's cost.
        DB::transaction(function () use ($piece, $input, $result, $body): void {
            AiCall::create([
                'team_id' => $piece->hotel->team_id,
                'hotel_id' => $piece->hotel_id,
                'scan_run_id' => null,
                'purpose' => AiPurpose::Content,
                'subject' => 'content:'.$piece->id,
                'model' => $result['model'],
                'tokens_in' => $result['tokens_in'],
                'tokens_out' => $result['tokens_out'],
                'cost_usd' => round($this->costs->tokens($result['model'], $result['tokens_in'], $result['tokens_out']), 6),
                'result' => ['type' => $piece->type->value, 'language' => $piece->language],
            ]);

            $piece->update([
                'status' => ContentStatus::Ready,
                'title' => Str::limit($result['title'] !== '' ? $result['title'] : $input->type->label(), 255, ''),
                'body' => $body,
            ]);
        });
    }

    /**
     * Content generated this month (team timezone) per team: cost and pieces, for Admin > Teams.
     *
     * @param  iterable<Team>  $teams
     * @return array<int, array{cost: float, pieces: int}>
     */
    public function monthlyTeamUsage(iterable $teams): array
    {
        $usage = [];

        foreach ($teams as $team) {
            $since = $team->currentPeriodStart();
            $usage[$team->id] = [
                'cost' => round((float) AiCall::query()->where('team_id', $team->id)->where('purpose', AiPurpose::Content->value)->where('created_at', '>=', $since)->sum('cost_usd'), 6),
                'pieces' => ContentPiece::query()->whereIn('hotel_id', $team->hotels()->pluck('id'))->where('created_at', '>=', $since)->where('status', '!=', ContentStatus::Failed->value)->count(),
            ];
        }

        return $usage;
    }

    public function fail(ContentPiece $piece, string $message): void
    {
        $piece->update(['status' => ContentStatus::Failed, 'error' => Str::limit($message, 480)]);
    }

    public function saveEdit(ContentPiece $piece, string $text): void
    {
        $text = trim($text);
        $piece->update(['edited_body' => $text === '' || $text === trim((string) $piece->body) ? null : $text]);
    }

    /**
     * Length limits of the fields this content goes into, shown next to the text.
     *
     * @return list<array{label: string, max: int, unit: string}>
     */
    public static function limitsFor(ContentType $type): array
    {
        $limits = (array) config('citevanta.content.limits', []);

        return match ($type) {
            ContentType::OtaListingUpdate => [
                ['label' => 'Booking.com "About the neighbourhood"', 'max' => (int) ($limits['booking_neighbourhood'] ?? 2000), 'unit' => 'characters'],
                ['label' => 'Agoda description', 'max' => (int) ($limits['agoda_description_words'] ?? 160), 'unit' => 'words'],
            ],
            ContentType::GoogleBusinessProfile => [
                ['label' => 'Description', 'max' => (int) ($limits['gbp_description'] ?? 750), 'unit' => 'characters'],
                ['label' => 'Post', 'max' => (int) ($limits['gbp_post'] ?? 1500), 'unit' => 'characters'],
            ],
            ContentType::ReviewRequest => [['label' => 'Message', 'max' => (int) ($limits['review_request'] ?? 600), 'unit' => 'characters']],
            default => [],
        };
    }
}
